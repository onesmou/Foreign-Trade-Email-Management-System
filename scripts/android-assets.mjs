// Build-time rasterization of the project's existing vector brand asset; no customer data.
import sharp from "sharp";
import { mkdir, unlink } from "node:fs/promises";
import path from "node:path";
const resource = path.resolve("android/app/src/main/res");
const logo = path.resolve("android/branding/logo.svg");
for (const [density, size] of [
  ["mdpi", 108],
  ["hdpi", 162],
  ["xhdpi", 216],
  ["xxhdpi", 324],
  ["xxxhdpi", 432],
]) {
  const folder = path.join(resource, `mipmap-${density}`);
  await mkdir(folder, { recursive: true });
  const inside = Math.round(size * (64 / 108));
  const image = await sharp(logo, { density: 300 })
    .resize(inside, inside, {
      fit: "contain",
      background: { r: 255, g: 255, b: 255, alpha: 0 },
    })
    .png()
    .toBuffer();
  await sharp({
    create: {
      width: size,
      height: size,
      channels: 4,
      background: { r: 255, g: 255, b: 255, alpha: 0 },
    },
  })
    .composite([{ input: image, gravity: "centre" }])
    .png()
    .toFile(path.join(folder, "brand_foreground.png"));
  // Remove only the exact legacy PNGs generated by an earlier run of this script.
  await unlink(path.join(folder, "ic_launcher.png")).catch((error) => {
    if (error.code !== "ENOENT") throw error;
  });
}
console.log("Android launcher assets built from existing company logo.");
